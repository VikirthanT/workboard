"""What the database itself enforces, written to directly so the API's own checks cannot help.

Every refusal is asserted by constraint name, so a test cannot pass because of some other, unrelated error.
"""
import itertools

import pytest
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError

from models import AccessAuditLog, Person, Task, TaskActivity, Team

_counter = itertools.count(1)


def make_person(**overrides) -> Person:
    n = next(_counter)
    fields = {"slack_user_id": f"D{n:04d}", "email": f"db{n}@atimotors.com", "name": f"Db {n}"}
    return Person(**{**fields, **overrides})


def refused(db, constraint: str, *rows):
    """Adding these rows must be refused by the named constraint; the session is left usable."""
    with pytest.raises(IntegrityError, match=constraint):
        db.add_all(rows)
        db.commit()
    db.rollback()


# ---- uniqueness ----

def test_two_people_cannot_share_an_email_or_a_slack_id(db):
    db.add(make_person(slack_user_id="D-one", email="same@atimotors.com"))
    db.commit()

    refused(db, "people_email_key", make_person(email="same@atimotors.com"))
    refused(db, "people_slack_user_id_key", make_person(slack_user_id="D-one"))


def test_team_names_are_unique_ignoring_case(db):
    db.add(Team(name="NPI"))
    db.commit()

    refused(db, "uq_teams_name_lower", Team(name="npi"))


def test_a_person_cannot_manage_two_teams(db):
    manager = make_person()
    db.add(manager)
    db.commit()
    db.add(Team(name="NPI", manager_id=manager.id))
    db.commit()

    refused(db, "teams_manager_id_key", Team(name="QA", manager_id=manager.id))


def test_a_team_cannot_have_two_manager_role_people(db):
    team = Team(name="NPI")
    db.add(team)
    db.commit()
    db.add(make_person(role="manager", team_id=team.id))
    db.commit()

    refused(db, "uq_people_one_manager_per_team", make_person(role="manager", team_id=team.id))
    # Plain members are unlimited, and a manager of a different team is fine.
    db.add_all([make_person(team_id=team.id), make_person(team_id=team.id)])
    db.commit()


