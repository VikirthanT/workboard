def test_email_must_be_lowercase(db):
    refused(db, "ck_people_email_lower", make_person(email="Mixed.Case@atimotors.com"))


def test_role_must_be_member_or_manager(db):
    refused(db, "ck_people_role", make_person(role="admin"))
    refused(db, "ck_people_role", make_person(role="boss"))


@pytest.mark.parametrize("column", ["slack_user_id", "email", "name", "role", "is_admin", "active"])
def test_required_person_columns_cannot_be_null(db, column):
    # Raw SQL on purpose: the ORM would replace an explicit None with the column's Python default.
    values = {"slack_user_id": "N1", "email": "n1@atimotors.com", "name": "N", "role": "member",
              "is_admin": False, "active": True, column: None}
    with pytest.raises(IntegrityError, match=f'null value in column "{column}"'):
        db.execute(text(
            "INSERT INTO people (slack_user_id, email, name, role, is_admin, active) "
            "VALUES (:slack_user_id, :email, :name, :role, :is_admin, :active)"
        ), values)
    db.rollback()


def test_a_team_must_have_a_name(db):
    with pytest.raises(IntegrityError, match='null value in column "name"'):
        db.execute(text("INSERT INTO teams (name) VALUES (NULL)"))
    db.rollback()


def test_a_team_must_point_at_a_real_person_and_a_person_at_a_real_team(db):
    ghost = "00000000-0000-0000-0000-000000000000"
    refused(db, "teams_manager_id_fkey", Team(name="Ghosted", manager_id=ghost))
    refused(db, "fk_people_team_id", make_person(team_id=ghost))


# ---- defaults ----

def test_the_database_fills_in_the_defaults(db):
    person = db.execute(text(
        "INSERT INTO people (slack_user_id, email, name) VALUES ('RAW1', 'raw1@atimotors.com', 'Raw One') "
        "RETURNING id, role, is_admin, active, team_id, created_at, updated_at"
    )).one()
    team = db.execute(text("INSERT INTO teams (name) VALUES ('Raw Team') RETURNING id, manager_id, active, created_at")).one()

    assert person.id is not None  # a UUID generated by gen_random_uuid()
    assert (person.role, person.is_admin, person.active, person.team_id) == ("member", False, True, None)
    assert person.created_at is not None and person.updated_at is not None
    assert team.id is not None and team.manager_id is None and team.active is True and team.created_at is not None
    db.rollback()


def test_updated_at_moves_when_the_app_changes_a_person(db):
    person = make_person()
    db.add(person)
    db.commit()
    created = person.updated_at

    person.name = "Renamed"
    db.commit()
    db.refresh(person)

    assert person.updated_at > created


# ---- what happens to related rows on delete ----

def test_deleting_a_team_releases_its_people_but_keeps_them(db):
    team = Team(name="NPI")
    db.add(team)
    db.commit()
    member = make_person(team_id=team.id)
    db.add(member)
    db.commit()

    db.execute(text("DELETE FROM teams WHERE id = :id"), {"id": team.id})
    db.commit()
    db.refresh(member)

    assert member.team_id is None


